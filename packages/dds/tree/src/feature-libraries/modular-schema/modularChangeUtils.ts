export function hasConflicts(change: ModularChangeset): boolean {
	return (change.constraintViolationCount ?? 0) > 0;
}

/**
 * Creates a normalized changeset from the provided properties.
 *
 * Required changeset maps are initialized when omitted, and empty optional properties are not
 * included in the returned changeset. `maxId` accepts an unbranded allocator ID; `undefined`
 * indicates that the changeset contains no IDs.
 */
export function makeModularChangeset(
	props: Partial<Omit<ModularChangeset, "maxId">> & { maxId?: number } = {},
): ModularChangeset {
	const p = props;
	const changeset: Mutable<ModularChangeset> = {
		fieldChanges: p.fieldChanges ?? new Map<FieldKey, FieldChange>(),
		nodeChanges: p.nodeChanges ?? newChangeAtomIdBTree(),
		nodeToParent: p.nodeToParent ?? newChangeAtomIdBTree(),
		nodeAliases: p.nodeAliases ?? newChangeAtomIdBTree(),
		crossFieldKeys: p.crossFieldKeys ?? newCrossFieldKeyTable(),
	};

	if (p.revisions !== undefined && p.revisions.length > 0) {
		changeset.revisions = p.revisions;
	}
	if (p.maxId !== undefined && p.maxId >= 0) {
		changeset.maxId = brand(p.maxId);
	}
	if (p.constraintViolationCount !== undefined && p.constraintViolationCount > 0) {
		changeset.constraintViolationCount = p.constraintViolationCount;
	}
	if (p.noChangeConstraint !== undefined) {
		changeset.noChangeConstraint = p.noChangeConstraint;
	}
	if (p.noChangeConstraintOnRevert !== undefined) {
		changeset.noChangeConstraintOnRevert = p.noChangeConstraintOnRevert;
	}
	if (p.builds !== undefined && p.builds.size > 0) {
		changeset.builds = p.builds;
	}
	if (p.destroys !== undefined && p.destroys.size > 0) {
		changeset.destroys = p.destroys;
	}
	if (p.refreshers !== undefined && p.refreshers.size > 0) {
		changeset.refreshers = p.refreshers;
	}
	return changeset;
}

// TODO: TFieldData could instead just be a numeric ID generated by the CrossFieldTable
// The CrossFieldTable could have a generic field ID to context table
export interface CrossFieldTable<TFieldData> {
	srcTable: CrossFieldMap<unknown>;
	dstTable: CrossFieldMap<unknown>;
	srcDependents: CrossFieldMap<TFieldData>;
	dstDependents: CrossFieldMap<TFieldData>;
	invalidatedFields: Set<TFieldData>;
}

export abstract class CrossFieldManagerI<T> implements CrossFieldManager {
	public constructor(
		protected readonly crossFieldTable: CrossFieldTable<T>,
		private readonly currentFieldKey: T,
		protected readonly allowInval = true,
	) {}

	public set(
		target: CrossFieldTarget,
		revision: RevisionTag | undefined,
		id: ChangesetLocalId,
		count: number,
		newValue: unknown,
		invalidateDependents: boolean,
	): void {
		if (invalidateDependents && this.allowInval) {
			const lastChangedId = (id as number) + count - 1;
			let firstId = id;
			while (firstId <= lastChangedId) {
				const dependentEntry = getFirstFromCrossFieldMap(
					this.getDependents(target),
					revision,
					firstId,
					lastChangedId - firstId + 1,
				);
				if (dependentEntry.value !== undefined) {
					this.crossFieldTable.invalidatedFields.add(dependentEntry.value);
				}

				firstId = brand(firstId + dependentEntry.length);
			}
		}
		setInCrossFieldMap(this.getMap(target), revision, id, count, newValue);
	}

	public get(
		target: CrossFieldTarget,
		revision: RevisionTag | undefined,
		id: ChangesetLocalId,
		count: number,
		addDependency: boolean,
	): RangeQueryResult<unknown> {
		if (addDependency) {
			// We assume that if there is already an entry for this ID it is because
			// a field handler has called compose on the same node multiple times.
			// In this case we only want to update the latest version, so we overwrite the dependency.
			setInCrossFieldMap(
				this.getDependents(target),
				revision,
				id,
				count,
				this.currentFieldKey,
			);
		}
		return getFirstFromCrossFieldMap(this.getMap(target), revision, id, count);
	}

	public abstract onMoveIn(id: NodeId): void;

	public abstract moveKey(
		target: CrossFieldTarget,
		revision: RevisionTag | undefined,
		id: ChangesetLocalId,
		count: number,
	): void;

	private getMap(target: CrossFieldTarget): CrossFieldMap<unknown> {
		return target === CrossFieldTarget.Source
			? this.crossFieldTable.srcTable
			: this.crossFieldTable.dstTable;
	}

	private getDependents(target: CrossFieldTarget): CrossFieldMap<T> {
		return target === CrossFieldTarget.Source
			? this.crossFieldTable.srcDependents
			: this.crossFieldTable.dstDependents;
	}
}

export function newCrossFieldTable<T>(): CrossFieldTable<T> {
	return {
		srcTable: newChangeAtomIdRangeMap(),
		dstTable: newChangeAtomIdRangeMap(),
		srcDependents: newChangeAtomIdRangeMap(),
		dstDependents: newChangeAtomIdRangeMap(),
		invalidatedFields: new Set(),
	};
}

export function getRevInfoFromTaggedChanges(changes: TaggedChange<ModularChangeset>[]): {
	revInfos: RevisionInfo[];
	maxId: ChangesetLocalId;
} {
	let maxId = -1;
	const revInfos: RevisionInfo[] = [];
	const revisions = new Set<RevisionTag>();
	for (const taggedChange of changes) {
		const change = taggedChange.change;
		maxId = Math.max(change.maxId ?? -1, maxId);
		const infosToAdd = revisionInfoFromTaggedChange(taggedChange);
		for (const info of infosToAdd) {
			if (!revisions.has(info.revision)) {
				revisions.add(info.revision);
				revInfos.push(info);
			}
		}
	}

	const rolledBackRevisions: RevisionTag[] = [];
	for (const info of revInfos) {
		if (info.rollbackOf !== undefined) {
			rolledBackRevisions.push(info.rollbackOf);
		}
	}

	rolledBackRevisions.reverse();
	for (const revision of rolledBackRevisions) {
		if (!revisions.has(revision)) {
			revInfos.push({ revision });
		}
	}

	return { maxId: brand(maxId), revInfos };
}

export function revisionInfoFromTaggedChange(
	taggedChange: TaggedChange<ModularChangeset>,
): RevisionInfo[] {
	const revInfos: RevisionInfo[] = [];
	if (taggedChange.change.revisions !== undefined) {
		revInfos.push(...taggedChange.change.revisions);
	} else if (taggedChange.revision !== undefined) {
		const info: Mutable<RevisionInfo> = { revision: taggedChange.revision };
		if (taggedChange.rollbackOf !== undefined) {
			info.rollbackOf = taggedChange.rollbackOf;
		}
		revInfos.push(info);
	}
	return revInfos;
}

export function getChangeHandler(
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
	kind: FieldKindIdentifier,
): FieldChangeHandler<unknown> {
	return getFieldKind(fieldKinds, kind).changeHandler;
}

function getFieldKind(
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
	kind: FieldKindIdentifier,
): FlexFieldKind {
	if (kind === genericFieldKind.identifier) {
		return genericFieldKind;
	}
	const fieldKind = fieldKinds.get(kind);
	assert(fieldKind !== undefined, 0x3ad /* Unknown field kind */);
	return fieldKind;
}

export interface ConstraintState {
	violationCount: number;
}

export function newConstraintState(violationCount: number): ConstraintState {
	return {
		violationCount,
	};
}

export function updateConstraintsForFields(
	fields: FieldChangeMap,
	parentInputAttachState: NodeAttachState,
	constraintState: ConstraintState,
	nodes: ChangeAtomIdBTree<NodeChangeset>,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): void {
	for (const field of fields.values()) {
		const handler = getChangeHandler(fieldKinds, field.fieldKind);
		for (const { nodeId, inputRootId } of handler.getNestedChanges(field.change)) {
			const isInputDetached = inputRootId !== undefined;
			const inputAttachState =
				parentInputAttachState === NodeAttachState.Detached || isInputDetached
					? NodeAttachState.Detached
					: NodeAttachState.Attached;

			updateConstraintsForNode(
				nodeId,
				inputAttachState,
				nodes,
				nodeAliases,
				constraintState,
				fieldKinds,
			);
		}
	}
}

function updateConstraintsForNode(
	nodeId: NodeId,
	inputAttachState: NodeAttachState,
	nodes: ChangeAtomIdBTree<NodeChangeset>,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
	constraintState: ConstraintState,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): void {
	const node = nodeChangeFromId(nodes, nodeId, nodeAliases);
	if (node.nodeExistsConstraint !== undefined) {
		const isNowViolated = inputAttachState === NodeAttachState.Detached;
		if (node.nodeExistsConstraint.violated !== isNowViolated) {
			node.nodeExistsConstraint = {
				...node.nodeExistsConstraint,
				violated: isNowViolated,
			};
			constraintState.violationCount += isNowViolated ? 1 : -1;
		}
	}

	if (node.fieldChanges !== undefined) {
		updateConstraintsForFields(
			node.fieldChanges,
			inputAttachState,
			constraintState,
			nodes,
			nodeAliases,
			fieldKinds,
		);
	}
}

export function nodeChangeFromId(
	nodes: ChangeAtomIdBTree<NodeChangeset>,
	id: NodeId,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
): NodeChangeset {
	const normalizedId = normalizeNodeId(id, nodeAliases);
	const node = getFromChangeAtomIdMap(nodes, normalizedId);
	assert(node !== undefined, 0x9ca /* Unknown node ID */);
	return node;
}

/**
 * @returns The canonical form of nodeId, according to nodeAliases
 */
export function normalizeNodeId(
	nodeId: NodeId,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
): NodeId {
	let currentId = nodeId;

	while (true) {
		const dealiased = getFromChangeAtomIdMap(nodeAliases, currentId);
		if (dealiased === undefined) {
			return currentId;
		}
		assert(!areEqualChangeAtomIds(dealiased, nodeId), "Node alias loop");

		currentId = dealiased;
	}
}

/**
 * Updates `nodeAliases` so that `alias1` and `alias2` are considered equivalent.
 * @param nodeAliases - The set of aliases to update.
 * @param alias1 - The first node ID to be considered equivalent.
 * @param alias2 - The second node ID to be considered equivalent.
 * @returns The normalized ID that both `alias1` and `alias2` map to as a result of unification.
 */
export function unifyAliases(
	nodeAliases: ChangeAtomIdBTree<NodeId>,
	alias1: NodeId,
	alias2: NodeId,
): NodeId {
	const normalizedAlias1 = normalizeNodeId(alias1, nodeAliases);
	const normalizedAlias2 = normalizeNodeId(alias2, nodeAliases);
	if (!areEqualChangeAtomIds(normalizedAlias1, normalizedAlias2)) {
		nodeAliases.set([normalizedAlias1.revision, normalizedAlias1.localId], normalizedAlias2);
	}
	return normalizedAlias2;
}

export function makeChangesetInversions(
	fields: FieldChangeMap,
	nodes: ChangeAtomIdBTree<NodeChangeset>,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
): { crossFieldKeys: CrossFieldKeyTable; nodeToParent: ChangeAtomIdBTree<FieldId> } {
	const crossFieldKeys: CrossFieldKeyTable = newCrossFieldKeyTable();
	const nodeToParent: ChangeAtomIdBTree<FieldId> = newChangeAtomIdBTree();
	populateInversionsFromFieldMap(
		fields,
		undefined,
		fieldKinds,
		crossFieldKeys,
		nodeToParent,
		nodeAliases,
	);

	nodes.forEachPair(([revision, localId], node) => {
		if (node.fieldChanges !== undefined) {
			populateInversionsFromFieldMap(
				node.fieldChanges,
				{
					revision,
					localId,
				},
				fieldKinds,
				crossFieldKeys,
				nodeToParent,
				nodeAliases,
			);
		}
	});

	return { crossFieldKeys, nodeToParent };
}

function populateInversionsFromFieldMap(
	fields: FieldChangeMap,
	parent: NodeId | undefined,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
	crossFieldKeys: CrossFieldKeyTable,
	nodeToParent: ChangeAtomIdBTree<FieldId>,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
): void {
	for (const [fieldKey, fieldChange] of fields) {
		const handler = getChangeHandler(fieldKinds, fieldChange.fieldKind);
		for (const { key, count } of handler.getCrossFieldKeys(fieldChange.change)) {
			crossFieldKeys.set(key, count, { nodeId: parent, field: fieldKey });
		}

		for (const { nodeId } of handler.getNestedChanges(fieldChange.change)) {
			const normalizedNodeId = normalizeNodeId(nodeId, nodeAliases);
			nodeToParent.set([normalizedNodeId.revision, normalizedNodeId.localId], {
				nodeId: parent,
				field: fieldKey,
			});
		}
	}
}

export function validateChangeset(
	change: ModularChangeset,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): void {
	for (const [revision, localId] of change.nodeChanges.keys()) {
		assert(
			!change.nodeAliases.has([revision, localId]),
			"Node change table contains a non-normalized node key",
		);
	}
	for (const [revision, localId] of change.nodeToParent.keys()) {
		assert(
			!change.nodeAliases.has([revision, localId]),
			"Node parentage table contains a non-normalized node key",
		);
	}

	const allChildren = validateFieldChanges(change, change.fieldChanges, undefined, fieldKinds);

	for (const [[revision, localId], node] of change.nodeChanges.entries()) {
		if (node.fieldChanges === undefined) {
			continue;
		}

		const nodeId: NodeId = { revision, localId };
		const fieldChildren = validateFieldChanges(change, node.fieldChanges, nodeId, fieldKinds);

		populatedNestedSet(fieldChildren, allChildren);
	}

	for (const [revision, localId] of change.nodeChanges.keys()) {
		assert(
			nestedSetContains(allChildren, revision, localId),
			"Node change table contains unparented node",
		);
	}
	for (const [revision, innerMap] of allChildren.entries()) {
		for (const localId of innerMap.keys()) {
			assert(
				change.nodeChanges.has([revision, localId]),
				"Node change table is missing a parented node",
			);
		}
	}
}

/**
 * Asserts that each child and cross field key in each field has a correct entry in
 * `nodeToParent` or `crossFieldKeyTable`.
 * @returns the number of children found.
 */
function validateFieldChanges(
	change: ModularChangeset,
	fieldChanges: FieldChangeMap,
	nodeParent: NodeId | undefined,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): NestedSet<NodeId["revision"], NodeId["localId"]> {
	const children: NestedSet<NodeId["revision"], NodeId["localId"]> = new Map();
	for (const [field, fieldChange] of fieldChanges.entries()) {
		const fieldId = normalizeFieldId({ nodeId: nodeParent, field }, change.nodeAliases);
		const handler = getChangeHandler(fieldKinds, fieldChange.fieldKind);
		for (const { nodeId } of handler.getNestedChanges(fieldChange.change)) {
			const normalizedNodeId = normalizeNodeId(nodeId, change.nodeAliases);
			const parentFieldId = normalizeFieldId(
				getParentFieldId(change, normalizedNodeId),
				change.nodeAliases,
			);
			assert(
				areEqualFieldIds(parentFieldId, fieldId),
				0xa4e /* Inconsistent node parentage */,
			);
			addToNestedSet(children, normalizedNodeId.revision, normalizedNodeId.localId);
		}

		for (const keyRange of handler.getCrossFieldKeys(fieldChange.change)) {
			const fields = getFieldsForCrossFieldKey(change, keyRange.key, keyRange.count);
			assert(
				fields.length === 1 && fields[0] !== undefined && areEqualFieldIds(fields[0], fieldId),
				0xa4f /* Inconsistent cross field keys */,
			);
		}
	}

	return children;
}

export interface ChangeStructure {
	readonly root: NodeChangeStructure;
	readonly aliases: readonly [NodeId, readonly NodeId[]][];
}
export type NodeChangeStructure = Readonly<Record<FieldKey, FieldChangeStructure>>;
export type FieldChangeStructure = readonly (readonly [NodeId, NodeId, NodeChangeStructure])[];
export function getChangeStructure(
	change: ModularChangeset,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): ChangeStructure {
	const aliasMap: NestedMap<NodeId["revision"], NodeId["localId"], NodeId[]> = new Map();
	for (const [[revision, localId], nodeId] of change.nodeAliases.entries()) {
		const normal = normalizeNodeId(nodeId, change.nodeAliases);
		const aliases = getOrCreateInNestedMap(
			aliasMap,
			normal.revision,
			normal.localId,
			() => [],
		);
		aliases.push({ revision, localId });
	}
	const aliasArray: [NodeId, readonly NodeId[]][] = [];
	for (const [revision, localMap] of aliasMap) {
		for (const [localId, nodeIds] of localMap) {
			aliasArray.push([{ revision, localId }, nodeIds]);
		}
	}
	return {
		root: getNodeChangeStructure(change, change.fieldChanges, fieldKinds),
		aliases: aliasArray,
	};
}

export function getNodeChangeStructure(
	change: ModularChangeset,
	field: FieldChangeMap,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): NodeChangeStructure {
	const nodeChangeStructure: Record<FieldKey, FieldChangeStructure> = {};
	for (const [fieldKey, fieldChange] of field) {
		nodeChangeStructure[fieldKey] = getFieldChangeStructure(change, fieldChange, fieldKinds);
	}
	return nodeChangeStructure;
}

export function getFieldChangeStructure(
	change: ModularChangeset,
	fieldChange: FieldChange,
	fieldKinds: ReadonlyMap<FieldKindIdentifier, FlexFieldKind>,
): FieldChangeStructure {
	const fieldChangeStructure: (readonly [NodeId, NodeId, NodeChangeStructure])[] = [];
	const handler = getChangeHandler(fieldKinds, fieldChange.fieldKind);

	for (const { nodeId } of handler.getNestedChanges(fieldChange.change)) {
		const normalized = normalizeNodeId(nodeId, change.nodeAliases);
		const nodeChanges = change.nodeChanges.get([normalized.revision, normalized.localId]);
		assert(nodeChanges !== undefined, "missing nested changes");
		fieldChangeStructure.push([
			nodeId,
			normalized,
			getNodeChangeStructure(change, nodeChanges.fieldChanges ?? new Map(), fieldKinds),
		]);
	}
	return fieldChangeStructure;
}

/**
 * Retrieves the normalized field ID of the parent field containing the specified node.
 * @param changeset - The modular changeset containing the node.
 * @param nodeId - The ID of the node whose parent field ID is to be retrieved. This ID need not be normalized.
 * @returns The normalized field ID of the parent field containing the specified node.
 */
export function getParentFieldId(changeset: ModularChangeset, nodeId: NodeId): FieldId {
	const normalizedNodeId = normalizeNodeId(nodeId, changeset.nodeAliases);
	const parentId = getFromChangeAtomIdMap(changeset.nodeToParent, normalizedNodeId);
	assert(parentId !== undefined, 0x9cb /* Parent field should be defined */);
	return normalizeFieldId(parentId, changeset.nodeAliases);
}

export function normalizeFieldId(
	fieldId: FieldId,
	nodeAliases: ChangeAtomIdBTree<NodeId>,
): FieldId {
	return fieldId.nodeId === undefined
		? fieldId
		: { ...fieldId, nodeId: normalizeNodeId(fieldId.nodeId, nodeAliases) };
}

export function getFieldsForCrossFieldKey(
	changeset: ModularChangeset,
	key: CrossFieldKey,
	count: number,
): FieldId[] {
	const fieldIds: FieldId[] = [];
	let nextOffset: number | undefined;
	for (const { value: fieldId, length, offset } of changeset.crossFieldKeys.getAll(
		key,
		count,
	)) {
		if (fieldId !== undefined) {
			const normalizedFieldId = normalizeFieldId(fieldId, changeset.nodeAliases);
			const previous = fieldIds.at(-1);
			const isContiguous =
				previous !== undefined &&
				areEqualFieldIds(previous, normalizedFieldId) &&
				offset === nextOffset;
			if (!isContiguous) {
				fieldIds.push(normalizedFieldId);
			}
			nextOffset = offset + length;
		}
	}

	return fieldIds;
}

function areEqualFieldIds(a: FieldId, b: FieldId): boolean {
	return areEqualChangeAtomIdOpts(a.nodeId, b.nodeId) && a.field === b.field;
}
