import { UsageError } from "@fluidframework/telemetry-utils/internal";

import type { IEncoder } from "../codec/index.js";
import type { TreeStoredSchema } from "../core/index.js";
import type { JsonCompatibleReadOnly } from "../util/index.js";
import type { ITreeViewConfigurationAlpha } from "./api/index.js";

/**
 * Computes a hash from the stored schema input supplied by SharedTree.
 *
 * @remarks
 * Import {@link computeSchemaHash} separately to use the standard hashing function.
 *
 * @param schema - the stored schema input generated by SharedTree
 *
 * @returns the schema hash
 *
 * @alpha
 */
export type SchemaHasher = (schema: JsonCompatibleReadOnly) => string;

/**
 * Checks a schema hash before initialization or schema upgrade.
 *
 * @param schema - the effective stored schema
 * @param identity - the expected hash and hashing function, or undefined to skip the check
 * @param encoder - the schema encoder selected by the tree
 */
export function validateSchemaHash(
	schema: TreeStoredSchema,
	identity: ITreeViewConfigurationAlpha["schemaIdentity"],
	encoder: IEncoder<TreeStoredSchema, JsonCompatibleReadOnly, void>,
): void {
	if (identity === undefined) {
		return;
	}
	const { schemaHash: expectedHash, schemaHasher: hasher } = identity;
	const actualHash = hasher(encoder.encode(schema));
	if (actualHash !== expectedHash) {
		throw new UsageError(
			`Schema hash does not match the effective schema. Expected ${JSON.stringify(expectedHash)}, computed ${JSON.stringify(actualHash)}. Regenerate schemaHash using the same staged upgrade selection and encoding options.`,
		);
	}
}
