import { UsageError } from "@fluidframework/telemetry-utils/internal";
import { sha256 } from "sha.js";

import {
	type CodecWriteOptions,
	FluidClientVersion,
	FormatValidatorNoOp,
} from "../../codec/index.js";
import { schemaCodecBuilder } from "../../feature-libraries/index.js";
import {
	compareStrings,
	isReadonlyArray,
	type JsonCompatibleReadOnly,
} from "../../util/index.js";
import type { SchemaUpgrade, StagedSchemaUpgradePolicy } from "../core/index.js";
import type { ImplicitFieldSchema } from "../fieldSchema.js";
import type { SchemaHasher } from "../schemaHash.js";
import { toInitialSchema } from "../toStoredSchema.js";

/**
 * Computes a hash from a view schema.
 *
 * @remarks
 * The provided view schema is converted to stored schema format with the provided
 * enabled staged upgrades before it is hashed.
 *
 * @param schema - the view schema to hash
 * @param stagedSchemaUpgrades - the staged upgrades to include
 * If not provided, no staged upgrades are included.
 * @param encodingOptions - the encoding options used by the tree, with version 2.0 compatibility
 * as the default
 *
 * @returns the SHA-256 hash of the encoded schema, in hexadecimal
 *
 * @alpha
 */
export function computeViewSchemaHash(
	schema: ImplicitFieldSchema,
	stagedSchemaUpgrades?: Iterable<SchemaUpgrade> | StagedSchemaUpgradePolicy,
	encodingOptions: Partial<Omit<CodecWriteOptions, "jsonValidator">> = {},
): string {
	const encoder = schemaCodecBuilder.build({
		minVersionForCollab: FluidClientVersion.v2_0,
		...encodingOptions,
		jsonValidator: FormatValidatorNoOp,
	});
	return computeSchemaHash(encoder.encode(toInitialSchema(schema, stagedSchemaUpgrades)));
}

/**
 * Computes a hash from a stored schema.
 *
 * @remarks
 * The hash includes the encoded schema and any metadata retained by its encoder.
 * Object key order and allowed-type order do not affect the hash, but metadata array order does.
 *
 * @param schema - the stored schema input generated by SharedTree
 *
 * @returns a hexadecimal SHA-256 hash
 *
 * @alpha
 */
export const computeSchemaHash: SchemaHasher = (schema) => {
	const serialized = JSON.stringify(schema);
	if (serialized === undefined) {
		throw new UsageError("Schema hash input must be JSON-serializable.");
	}
	// Match the persisted JSON representation before sorting object keys.
	const persisted = JSON.parse(serialized) as JsonCompatibleReadOnly;
	return new sha256().update(canonicalize(persisted)).digest("hex");
};

/**
 * Serializes JSON with sorted object keys so key order does not affect the hash.
 */
function canonicalize(value: JsonCompatibleReadOnly | undefined): string {
	if (value === undefined) {
		throw new UsageError("Canonical schema hash input cannot contain undefined.");
	}
	if (value === null || typeof value !== "object") {
		return JSON.stringify(value);
	}
	if (isReadonlyArray(value)) {
		return `[${value.map((item) => canonicalize(item)).join(",")}]`;
	}
	return `{${Object.entries(value)
		.sort(([a], [b]) => compareStrings(a, b))
		.map(([key, item]) => `${JSON.stringify(key)}:${canonicalize(item)}`)
		.join(",")}}`;
}
