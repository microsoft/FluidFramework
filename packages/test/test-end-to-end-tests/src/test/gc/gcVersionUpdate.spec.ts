import { strict as assert } from "assert";

import { describeCompat } from "@fluid-private/test-version-utils";
import { IContainer } from "@fluidframework/container-definitions/internal";
import type {
	IContainerRuntimeOptions,
	ISummarizer,
} from "@fluidframework/container-runtime/internal";
import {
	IGCMetadata,
	IGarbageCollector,
	IGarbageCollectorConfigs,
} from "@fluidframework/container-runtime/internal/test/gc";
import { IContainerRuntime } from "@fluidframework/container-runtime-definitions/internal";
import { ISummaryTree, SummaryType } from "@fluidframework/driver-definitions";
import { channelsTreeName, gcTreeKey } from "@fluidframework/runtime-definitions/internal";
import {
	ITestFluidObject,
	ITestObjectProvider,
	TestFluidObjectFactory,
	createContainerRuntimeFactoryWithDefaultDataStore,
	createSummarizerFromFactory,
	defaultTestOldestSupportedClient,
	summarizeNow,
	waitForContainerConnection,
} from "@fluidframework/test-utils/internal";
import { createSandbox, SinonSandbox } from "sinon";

// IContainerRuntime type that exposes garbage collector which is a private property.
type IContainerRuntimeWithPrivates = IContainerRuntime & {
	readonly garbageCollector: IGarbageCollector;
};

/**
 * Validates that when the runtime GC version changes, we reset the GC state and disable GC if needed.
 * Basically, when we update the GC version due to bugs, newer versions re-run GC and older versions stop running GC.
 *
 * Both the "newer" and "older" GC version scenarios are validated by a single test which chains summarizer clients
 * together. This keeps the coverage of both scenarios while only paying for one container setup / tear down cycle.
 */
describeCompat("GC version update", "NoCompat", (getTestObjectProvider, apis) => {
	const {
		containerRuntime: { ContainerRuntimeFactoryWithDefaultDataStore },
	} = apis;
	let provider: ITestObjectProvider;
	// TODO:#4670: Make this compat-version-specific.
	const defaultFactory = new TestFluidObjectFactory([]);
	const runtimeOptions: IContainerRuntimeOptions = {
		summaryOptions: {
			summaryConfigOverrides: {
				state: "disabled",
			},
		},
	};

	const defaultRuntimeFactory = createContainerRuntimeFactoryWithDefaultDataStore(
		ContainerRuntimeFactoryWithDefaultDataStore,
		{
			defaultFactory,
			oldestSupportedClient: defaultTestOldestSupportedClient,
			registryEntries: [[defaultFactory.type, Promise.resolve(defaultFactory)]],
			runtimeOptions,
		},
	);

	let mainContainer: IContainer;
	let dataStore1Id: string;
	let dataStore2Id: string;
	let dataStore3Id: string;

	/**
	 * Generates a summary and validates that the data store's summary is of correct type - tree or handle.
	 * The data stores ids in dataStoresAsHandles should have their summary as handles. All other data stores
	 * should have their summary as tree.
	 */
	async function summarizeAndValidateDataStoreState(
		summarizer: ISummarizer,
		dataStoresAsHandles: string[],
		gcAllowed: boolean,
	) {
		await provider.ensureSynchronized();
		const summaryResult = await summarizeNow(summarizer);

		const gcTreeExists = summaryResult.summaryTree.tree[gcTreeKey] !== undefined;
		assert.strictEqual(gcTreeExists, gcAllowed, "GC tree in summary is not as expected.");

		const dataStoreTrees = (summaryResult.summaryTree.tree[channelsTreeName] as ISummaryTree)
			.tree;
		for (const [key, value] of Object.entries(dataStoreTrees)) {
			if (dataStoresAsHandles.includes(key)) {
				assert(
					value.type === SummaryType.Handle,
					`The summary for data store ${key} should be a handle`,
				);
			} else {
				assert(
					value.type === SummaryType.Tree,
					`The summary for data store ${key} should be a tree`,
				);
			}
		}
		return summaryResult.summaryVersion;
	}

	/**
	 * Validates that the GC state is reset (empty) in the base GC details. This will ensure that the GC data is
	 * regenerated by all the nodes.
	 * A summary is done to ensure that the base GC details are initialized. The version of that summary is returned
	 * so that it can be used as the base snapshot of a subsequent summarizer.
	 */
	async function summarizeAndValidateGCStateReset(summarizer: ISummarizer): Promise<string> {
		const containerRuntime = (summarizer as any).runtime as IContainerRuntimeWithPrivates;
		const spy = sandbox.spy(containerRuntime.garbageCollector, "getBaseGCDetails");

		await provider.ensureSynchronized();
		const summaryResult = await summarizeNow(summarizer);

		assert.strictEqual(spy.callCount, 1, "Base GC details should have been fetched once");
		const baseGCDetails = await spy.returnValues[0];
		assert.deepStrictEqual(baseGCDetails, {}, "Base GC state should have been reset");

		// Since the GC state was reset, the GC data must have been regenerated and written as a tree (as opposed to a
		// handle to the GC tree in the previous summary). This also makes this summary usable as the base snapshot of
		// a subsequent summarizer.
		assert.strictEqual(
			summaryResult.summaryTree.tree[gcTreeKey]?.type,
			SummaryType.Tree,
			"GC data should have been regenerated in the summary",
		);
		return summaryResult.summaryVersion;
	}

	/**
	 * Validates that the GC version in the given summarizer's base snapshot differs from the GC version in effect by
	 * `expectedGCVersionDiff`, which is the scenario that must result in the GC state being reset.
	 * Validating this explicitly ensures that the GC state reset validation above cannot pass for an unrelated reason,
	 * such as the base snapshot not containing any GC data at all.
	 */
	function validateGCVersionInBaseSnapshot(
		summarizer: ISummarizer,
		expectedGCVersionDiff: number,
	) {
		const containerRuntime = (summarizer as any).runtime as IContainerRuntimeWithPrivates;
		const configs = JSON.parse(
			containerRuntime.garbageCollector.serializedConfigs,
		) as IGarbageCollectorConfigs;
		assert(configs.gcAllowed, "GC should be allowed");
		assert.strictEqual(
			configs.gcVersionInBaseSnapshot,
			configs.gcVersionInEffect + expectedGCVersionDiff,
			"The GC version in the base snapshot is not as expected",
		);
	}

	/**
	 * Function that sets up a container such that the GC version is the metadata blob in summary is updated as per
	 * gcVersionDiff param. It either increments or decrements the version to provide the ability to test clients
	 * running different GC versions.
	 */
	function setupGCVersionUpdateInMetadata(summarizer: ISummarizer, gcVersionDiff: number) {
		// Override the getMetadata function in GarbageCollector to update the gcFeature property.
		const containerRuntime = (summarizer as any).runtime as IContainerRuntimeWithPrivates;
		const garbageCollector = containerRuntime.garbageCollector;
		const getMetadataFunc = garbageCollector.getMetadata.bind(garbageCollector);
		garbageCollector.getMetadata = (): IGCMetadata => {
			const metadata = getMetadataFunc();
			const gcFeature = metadata.gcFeature;
			assert(gcFeature !== undefined, "gcFeature not found in GC metadata");
			return {
				...metadata,
				gcFeature: gcFeature + gcVersionDiff,
			};
		};
	}

	let sandbox: SinonSandbox;
	before(() => {
		sandbox = createSandbox();
	});

	beforeEach("setup", async () => {
		provider = getTestObjectProvider({ syncSummarizer: true });
		mainContainer = await provider.createContainer(defaultRuntimeFactory);
		const dataStore1 = (await mainContainer.getEntryPoint()) as ITestFluidObject;
		dataStore1Id = dataStore1.context.id;

		// Create couple more data stores and mark them as referenced.
		const containerRuntime = dataStore1.context.containerRuntime;
		const createDataStore = async (): Promise<ITestFluidObject> => {
			const dataStore = await containerRuntime.createDataStore(defaultFactory.type);
			return (await dataStore.entryPoint.get()) as ITestFluidObject;
		};
		const [dataStore2, dataStore3] = await Promise.all([createDataStore(), createDataStore()]);
		dataStore1.root.set("dataStore2", dataStore2.handle);
		dataStore1.root.set("dataStore3", dataStore3.handle);
		dataStore2Id = dataStore2.context.id;
		dataStore3Id = dataStore3.context.id;

		await waitForContainerConnection(mainContainer);
	});

	afterEach(() => {
		sandbox.restore();
	});

	/**
	 * Validates that the GC state is reset when the GC version in a client differs from the one in its base snapshot.
	 * Both directions of the mismatch are validated - a client whose GC version is newer than the one in its base
	 * snapshot, and a client whose GC version is older than the one in its base snapshot.
	 * The summarizers are chained so that both scenarios reuse the container setup done in beforeEach.
	 */
	it("should reset GC state when GC version is different than the one in base snapshot", async () => {
		// Stores the ids of data stores whose summary tree should be handles.
		const dataStoresAsHandles: string[] = [];

		// Create a summarizer client.
		const { summarizer: summarizer1 } = await createSummarizerFromFactory(
			provider,
			mainContainer,
			defaultFactory,
		);
		// Setup the summarizer container's GC version in summary to be decremented by 1 so that containers that load
		// from this summary will have newer GC version.
		setupGCVersionUpdateInMetadata(summarizer1, -1 /* gcVersionDiff */);

		// Generate a summary and validate that all data store summaries are trees.
		await summarizeAndValidateDataStoreState(
			summarizer1,
			dataStoresAsHandles,
			true /* gcAllowed */,
		);

		// Generate another summary in which the summaries for all data stores are handles. This validates that the
		// GC data is not regenerated in absence of changes.
		dataStoresAsHandles.push(dataStore1Id, dataStore2Id, dataStore3Id);
		const summaryVersion1 = await summarizeAndValidateDataStoreState(
			summarizer1,
			dataStoresAsHandles,
			true /* gcAllowed */,
		);

		// Create a new summarizer. It will have newer GC version that the above container.
		summarizer1.close();
		const { summarizer: summarizer2 } = await createSummarizerFromFactory(
			provider,
			mainContainer,
			defaultFactory,
			summaryVersion1,
		);
		validateGCVersionInBaseSnapshot(summarizer2, -1 /* expectedGCVersionDiff */);

		// Setup this summarizer container's GC version in summary to be incremented by 1 so that containers that load
		// from its summary will have older GC version. This lets the older GC version scenario below reuse the
		// container setup that the newer GC version scenario above already did.
		setupGCVersionUpdateInMetadata(summarizer2, 1 /* gcVersionDiff */);

		// Validate that the GC state is reset (empty) in the base GC details. When the GC state is empty, all the nodes
		// will start with empty GC data and will regenerate the GC data in the first GC / summary run.
		const summaryVersion2 = await summarizeAndValidateGCStateReset(summarizer2);

		// Create a new summarizer. It will have older GC version that the above container.
		summarizer2.close();
		const { summarizer: summarizer3 } = await createSummarizerFromFactory(
			provider,
			mainContainer,
			defaultFactory,
			summaryVersion2,
		);
		validateGCVersionInBaseSnapshot(summarizer3, 1 /* expectedGCVersionDiff */);

		// Validate that the GC state is reset (empty) in the base GC details in this scenario as well.
		await summarizeAndValidateGCStateReset(summarizer3);
	});
});
