/** Blob-tree identity generated by the Sea bindings. */
export type GeneratedSeaTreeId = SeaTreeId;

/** Generated remote or explicit process-local test-support client. */
export type GeneratedSeaClient = SeaInjectedClient | SeaLocalClient;

type GeneratedSeaStream = SeaInjectedStream | SeaLocalStream;
type GeneratedSnapshotStream = SeaInjectedSnapshotStream | SeaLocalSnapshotStream;

/** Application-facing snapshot publication participation policy. */
export type SnapshotParticipation = "ReadOnly" | "SeaSelected" | "ClientSelected";

/** Constructors and discriminants generated by wasm-bindgen. */
export interface GeneratedSeaTypes {
	loadKind: {
		readonly snapshot: SeaLoadKind.Snapshot;
		readonly event: SeaLoadKind.Event;
		readonly progress: SeaLoadKind.Progress;
	};
	streamStatus: {
		readonly awaitingNewItems: SeaStreamStatus.AwaitingNewItems;
	};
	treeKind: {
		readonly blob: SeaTreeKind.Blob;
		readonly directory: SeaTreeKind.Directory;
	};
	blob(bytes: Uint8Array): SeaTreeId;
	directory(bytes: Uint8Array): SeaTreeId;
	directoryEntry(name: string, child: SeaTreeId): SeaDirectoryEntry;
}

/** Generated module values needed to adapt either production or test-support clients. */
export interface GeneratedSeaModule {
	readonly SeaLoadKind: {
		readonly Snapshot: SeaLoadKind.Snapshot;
		readonly Event: SeaLoadKind.Event;
		readonly Progress: SeaLoadKind.Progress;
	};
	readonly SeaStreamStatus: {
		readonly AwaitingNewItems: SeaStreamStatus.AwaitingNewItems;
	};
	readonly SeaTreeKind: {
		readonly Blob: SeaTreeKind.Blob;
		readonly Directory: SeaTreeKind.Directory;
	};
	readonly SeaTreeId: {
		blob(bytes: Uint8Array): SeaTreeId;
		directory(bytes: Uint8Array): SeaTreeId;
	};
	readonly SeaDirectoryEntry: new (name: string, child: SeaTreeId) => SeaDirectoryEntry;
	readonly SeaSnapshotParticipation: {
		readonly ReadOnly: number;
		readonly SeaSelected: number;
		readonly ClientSelected: number;
	};
}

/** Adapts one generated production or test-support client to the Sea driver contract. */
export function createGeneratedSeaBindingAdapter(
	client: GeneratedSeaClient,
	bindings: GeneratedSeaModule,
	participation: SnapshotParticipation,
	reconnectTransport?: () => Promise<AsyncRequestTransport>,
): SeaDriverClient {
	return new GeneratedSeaBindingAdapter(
		client,
		{
			loadKind: {
				snapshot: bindings.SeaLoadKind.Snapshot,
				event: bindings.SeaLoadKind.Event,
				progress: bindings.SeaLoadKind.Progress,
			},
			streamStatus: {
				awaitingNewItems: bindings.SeaStreamStatus.AwaitingNewItems,
			},
			treeKind: {
				blob: bindings.SeaTreeKind.Blob,
				directory: bindings.SeaTreeKind.Directory,
			},
			blob: bindings.SeaTreeId.blob,
			directory: bindings.SeaTreeId.directory,
			directoryEntry: (name, child) => new bindings.SeaDirectoryEntry(name, child),
		},
		bindings.SeaSnapshotParticipation[participation],
		reconnectTransport,
	);
}

interface DirectoryNode {
	readonly children: Map<string, DirectoryNode | SeaTreeId>;
}

const encoder = new TextEncoder();
const decoder = new TextDecoder();

/** Adapts generated Sea methods to the driver's transport-neutral client surface. */
export class GeneratedSeaBindingAdapter implements SeaDriverClient {
	private readonly positionSequences = new Map<bigint, bigint>();
	private readonly sequencePositions = new Map<bigint, bigint>();
	private readonly operationLocalSequences = new Map<string, bigint>();
	private nextSequence = 1n;
	private eventStream: GeneratedSeaStream | undefined;
	private snapshotStream: GeneratedSnapshotStream | undefined;
	private eventResumeAfter: bigint | undefined;

	public constructor(
		private readonly client: GeneratedSeaClient,
		private readonly types: GeneratedSeaTypes,
		private readonly snapshotParticipation: number,
		private readonly reconnectTransport?: () => Promise<AsyncRequestTransport>,
	) {}

	public async create(): Promise<Uint8Array> {
		return this.client.createDocument(
			encoder.encode(`create-${crypto.randomUUID()}`),
			encoder.encode(`create-session-${crypto.randomUUID()}`),
		);
	}

	public async openSession(
		document: Uint8Array,
		writer: Uint8Array,
		session: Uint8Array,
		resumeAfter?: Uint8Array,
	): Promise<void> {
		await this.closeEventStream();
		await this.closeSnapshotStream();
		const reference = decodePosition(resumeAfter);
		await this.client.openSession(document, false, writer, session, reference);
		this.positionSequences.clear();
		this.sequencePositions.clear();
		this.nextSequence = 1n;
		await this.readProjected();
		this.eventStream = await this.client.read(reference);
		this.snapshotStream = await (
			this.client.subscribeSnapshots as (
				participation: number,
			) => Promise<GeneratedSnapshotStream>
		)(this.snapshotParticipation);
		await this.snapshotStream.next();
		this.eventResumeAfter = reference;
	}

	public async submitEvent(
		submission: Uint8Array,
		localSequenceNumber: number,
		payload: Uint8Array,
		referencePosition?: Uint8Array,
	): Promise<Uint8Array> {
		this.operationLocalSequences.set(bytesKey(submission), BigInt(localSequenceNumber));
		const receipt = await this.client.submit(
			submission,
			decodePosition(referencePosition),
			payload,
		);
		return encodePosition(receipt);
	}

	public async latestSnapshot(): Promise<
		| { readonly id: Uint8Array; readonly root: Uint8Array; readonly atEvent?: Uint8Array }
		| undefined
	> {
		const snapshot = await this.client.latestSnapshot();
		return snapshot === undefined
			? undefined
			: {
					id: encodePosition(snapshot.atEvent),
					root: snapshot.root.bytes,
					atEvent: encodePosition(snapshot.atEvent),
				};
	}

	public async snapshot(
		id: Uint8Array,
	): Promise<
		| { readonly id: Uint8Array; readonly root: Uint8Array; readonly atEvent?: Uint8Array }
		| undefined
	> {
		const position = decodePosition(id);
		if (position === undefined) {
			throw new Error("snapshot position is required");
		}
		const snapshot = await this.client.getSnapshot(position);
		return snapshot === undefined || snapshot.atEvent !== position
			? undefined
			: {
					id: encodePosition(snapshot.atEvent),
					root: snapshot.root.bytes,
					atEvent: encodePosition(snapshot.atEvent),
				};
	}

	public async publishSnapshotRoot(
		expectedParent: Uint8Array | undefined,
		atEvent: Uint8Array | undefined,
		root: Uint8Array,
	): Promise<Uint8Array> {
		let position = decodePosition(atEvent) ?? this.sequencePositions.get(0n);
		if (position === undefined) {
			if (expectedParent !== undefined || this.nextSequence !== 1n) {
				throw new Error("a snapshot must reference a known application position");
			}
			position = await this.client.submit(
				encoder.encode("fluid-initialize-v1"),
				undefined,
				encoder.encode(JSON.stringify({ seaFluid: "initialize", version: 1 })),
				this.types.directory(root),
			);
			this.positionSequences.set(position, 0n);
			this.sequencePositions.set(0n, position);
		}
		const snapshot = await this.client.publishSnapshot(
			decodePosition(expectedParent),
			position,
			this.types.directory(root),
		);
		return encodePosition(snapshot.atEvent);
	}

	public async readProjected(after?: Uint8Array): Promise<ProjectedReadPage> {
		const stream = await this.client.read(decodePosition(after));
		const operations: ProjectedOperation[] = [];
		let cursor = after;
		try {
			for (;;) {
				const item = await stream.next();
				if (item === undefined) {
					return cursor === undefined ? { operations } : { operations, cursor };
				}
				if (item.kind === this.types.loadKind.event) {
					const operation = this.project(item);
					if (operation !== undefined) {
						operations.push(operation);
					}
					cursor = encodePosition(item.position);
				} else if (
					item.kind === this.types.loadKind.progress &&
					item.status === this.types.streamStatus.awaitingNewItems
				) {
					return cursor === undefined ? { operations } : { operations, cursor };
				}
			}
		} finally {
			await stream.cancel();
		}
	}

	public async subscribeProjected(
		after?: Uint8Array,
	): Promise<ProjectedOperationSubscription> {
		if (decodePosition(after) !== this.eventResumeAfter) {
			throw new Error("Sea subscription position does not match its opened event stream");
		}
		const stream = this.eventStream;
		if (stream === undefined) {
			throw new Error("Sea event stream is not open");
		}
		this.eventStream = undefined;
		return {
			next: async () => {
				for (;;) {
					const item = await stream.next();
					if (item === undefined) {
						throw new Error("Sea subscription ended");
					}
					if (item.kind === this.types.loadKind.event) {
						const operation = this.project(item);
						if (operation !== undefined) {
							return operation;
						}
					}
				}
			},
			cancel: () => stream.cancel(),
		};
	}

	public async resolveSubmission(submission: Uint8Array): Promise<SubmissionResolution> {
		const receipt = await this.client.resolveSubmission(submission);
		if (receipt !== undefined && !this.positionSequences.has(receipt)) {
			await this.readProjected();
		}
		return receipt === undefined
			? { kind: "notCommitted" }
			: {
					kind: "committed",
					position: encodePosition(receipt),
					sequenceNumber: this.sequence(receipt),
				};
	}

	public async uploadBlob(payload: Uint8Array): Promise<BlobUpload> {
		const id = await this.client.putBlob(payload);
		return { digest: id.bytes, sizeBytes: BigInt(payload.length), deduplicated: false };
	}

	public fetchBlob(digest: Uint8Array): Promise<Uint8Array> {
		return this.client.getBlob(this.types.blob(digest));
	}

	public async publishSummary(entries: readonly SummaryEntry[]): Promise<SummaryPublication> {
		const root: DirectoryNode = { children: new Map() };
		for (const entry of entries) {
			insert(root, decoder.decode(entry.path).split("/"), this.types.blob(entry.blob));
		}
		const tree = await this.publishDirectory(root);
		return {
			digest: tree.bytes,
			entryCount: entries.length,
			persistedBytes: 0n,
			deduplicated: false,
		};
	}

	public async fetchSummary(digest: Uint8Array): Promise<readonly SummaryEntry[]> {
		const entries: SummaryEntry[] = [];
		await this.flattenDirectory(this.types.directory(digest), "", entries);
		return entries;
	}

	/** Releases local ownership; a closing transport may reject asynchronous cleanup. */
	public disconnect(): void {
		void this.closeEventStream().catch(() => {});
		void this.closeSnapshotStream().catch(() => {});
		this.client.disconnect();
	}

	public positionForSequence(sequenceNumber: number): Uint8Array | undefined {
		if (!Number.isSafeInteger(sequenceNumber) || sequenceNumber < 0) {
			throw new RangeError(`invalid Fluid sequence number ${sequenceNumber}`);
		}
		const position = this.sequencePositions.get(BigInt(sequenceNumber));
		return position === undefined ? undefined : encodePosition(position);
	}

	public async reconnect(..._args: readonly unknown[]): Promise<void> {
		if (this.reconnectTransport === undefined) {
			throw new Error("no Sea reconnect transport factory was configured");
		}
		this.client.replaceTransport(await this.reconnectTransport());
	}

	private async closeEventStream(): Promise<void> {
		const stream = this.eventStream;
		this.eventStream = undefined;
		this.eventResumeAfter = undefined;
		await stream?.cancel();
	}

	private async closeSnapshotStream(): Promise<void> {
		const stream = this.snapshotStream;
		this.snapshotStream = undefined;
		await stream?.cancel();
	}

	private project(item: SeaEventLoadResult): ProjectedOperation | undefined {
		const message = JSON.parse(decoder.decode(item.payload)) as {
			clientSequenceNumber?: number;
			seaFluid?: string;
			version?: number;
		};
		if (message.seaFluid === "initialize") {
			const previous = this.sequencePositions.get(0n);
			if (
				message.version !== 1 ||
				item.blobTree?.kind !== this.types.treeKind.directory ||
				(previous !== undefined ? previous !== item.position : this.nextSequence !== 1n)
			) {
				throw new Error("invalid Fluid initialization event");
			}
			this.positionSequences.set(item.position, 0n);
			this.sequencePositions.set(0n, item.position);
			return undefined;
		}
		const localSequenceNumber =
			this.operationLocalSequences.get(bytesKey(item.operation)) ??
			BigInt(message.clientSequenceNumber ?? 0);
		return {
			position: encodePosition(item.position),
			sequenceNumber: this.sequence(item.position),
			...(item.minimumReference === undefined
				? {}
				: { minimumReference: encodePosition(item.minimumReference) }),
			writer: item.author,
			session: item.session,
			submission: item.operation,
			localSequenceNumber,
			...(item.reference === undefined ? {} : { reference: encodePosition(item.reference) }),
			payload: item.payload,
		};
	}

	private sequence(position: bigint): bigint {
		const existing = this.positionSequences.get(position);
		if (existing !== undefined) {
			return existing;
		}
		const sequence = this.nextSequence++;
		this.positionSequences.set(position, sequence);
		this.sequencePositions.set(sequence, position);
		return sequence;
	}

	private async publishDirectory(node: DirectoryNode): Promise<SeaTreeId> {
		const entries: SeaDirectoryEntry[] = [];
		for (const [name, child] of [...node.children].sort(([left], [right]) =>
			left.localeCompare(right),
		)) {
			const id = "children" in child ? await this.publishDirectory(child) : child;
			entries.push(this.types.directoryEntry(name, id));
		}
		return this.client.putDirectory(entries);
	}

	private async flattenDirectory(
		directory: SeaTreeId,
		prefix: string,
		entries: SummaryEntry[],
	): Promise<void> {
		for (const entry of await this.client.getDirectory(directory)) {
			const path = prefix.length === 0 ? entry.name : `${prefix}/${entry.name}`;
			if (entry.child.kind === this.types.treeKind.directory) {
				await this.flattenDirectory(entry.child, path, entries);
			} else {
				entries.push({ path: encoder.encode(path), blob: entry.child.bytes });
			}
		}
	}
}

function bytesKey(bytes: Uint8Array): string {
	return Array.from(bytes, (value) => value.toString(16).padStart(2, "0")).join("");
}

function insert(directory: DirectoryNode, parts: readonly string[], leaf: SeaTreeId): void {
	const [name, ...rest] = parts;
	if (name === undefined || name.length === 0) {
		throw new Error("summary path contains an empty segment");
	}
	if (rest.length === 0) {
		directory.children.set(name, leaf);
		return;
	}
	const existing = directory.children.get(name);
	if (existing !== undefined && !("children" in existing)) {
		throw new Error("summary path collides with a blob");
	}
	const child = existing ?? { children: new Map<string, DirectoryNode | SeaTreeId>() };
	directory.children.set(name, child);
	insert(child as DirectoryNode, rest, leaf);
}

/** Encodes an event position without projecting through a JavaScript number. */
export function encodePosition(position: bigint): Uint8Array {
	const bytes = new Uint8Array(8);
	new DataView(bytes.buffer).setBigUint64(0, position);
	return bytes;
}

/** Decodes one canonical event position. */
export function decodePosition(position?: Uint8Array): bigint | undefined {
	if (position === undefined) {
		return undefined;
	}
	if (position.length !== 8) {
		throw new Error("Sea event position must contain exactly eight bytes");
	}
	return new DataView(position.buffer, position.byteOffset, position.byteLength).getBigUint64(
		0,
	);
}
