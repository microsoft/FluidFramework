// tenant-admin -- tenant lifecycle CLI for the self-hosted Fluid stack.
//
// Talks to riddler (tenant records) and gitrest (snapshot storage) over plain HTTP. Both are
// ClusterIP-only Services with no authentication, so this must run somewhere that can already
// reach them: inside the cluster (the normal path -- see ../tenant-admin.sh) or
// through `kubectl port-forward` with --riddler-url/--gitrest-url pointed at the forwarded ports.
//
// Output is JSON on stdout and human-readable notes on stderr, so it composes with jq and with
// the wrapper script while still being readable when run by hand.
//
// Run `tenant-admin help` for usage.

"use strict";

const { GitrestClient } = require("../src/gitrestClient");
const { KeyVaultAccessError, getSecret } = require("../src/keyVaultClient");
const { RiddlerClient } = require("../src/riddlerClient");
const { TenantManager } = require("../src/tenantManager");
const { ValidationError, normalizeTenantId } = require("../src/validation");
const { secretNameForTenant } = require("../src/keyVaultGuard");
const { randomUUID } = require("node:crypto");

const USAGE = `
tenant-admin -- manage tenants on a self-hosted Fluid stack

USAGE
  tenant-admin <command> [options]

COMMANDS
  create <tenantId> --contact <email>   Create a tenant (provisions storage, then registers it)
  get <tenantId>                        Show a tenant's configuration
  list [--include-disabled]             List tenants
  get-key <tenantId> [--key <name>]     PRIVILEGED. Print the tenant's signing keys; --key
                                        key1|key2 prints only that one
  rotate <tenantId> --key <name>        PRIVILEGED. Rotate key1 or key2
  set-contact <tenantId> --contact <email>
                                        Update the tenant admin contact
  delete <tenantId> [--purge-in-days N | --purge-now]
                                        Soft-delete by default; --purge-now removes the record
  help                                  Show this message

COMMON OPTIONS
  --riddler-url <url>       default http://fluid-riddler   (env TENANT_ADMIN_RIDDLER_URL)
  --gitrest-url <url>       default http://gitrest         (env TENANT_ADMIN_GITREST_URL)
  --historian-url <url>     default http://historian       (env TENANT_ADMIN_HISTORIAN_URL)
  --storage-owner <owner>   default fluid                  (env TENANT_ADMIN_STORAGE_OWNER)
  --storage-url <url>       gitrest URL recorded IN the tenant document; defaults to
                            --gitrest-url. Set this when reaching gitrest through a
                            port-forward, so the stored URL stays cluster-resolvable.
  --requestor <who>         recorded as createdBy/lastModifiedBy
                            (env TENANT_ADMIN_REQUESTOR)
  --timeout-ms <n>          per-request timeout, default 30000
  --json                    print only JSON (suppress the human-readable notes)
  --force                   override safety checks: allow rotate / delete on a tenant that
                            tenant-admin did not create (i.e. one seeded by Helm), and allow
                            rotating a key that a token service is actively using. See NOTES.

ROTATE SAFETY CHECK
  --keyvault-name <name>    vault the token service reads this tenant's signing key from.
                            Supplied by tenant-admin.sh from deploy.parameters.json. The secret
                            is read from inside the cluster as the AKS workload identity, over
                            the vault's private endpoint -- nothing is opened to the internet.
                            Omitted (or running this CLI outside the cluster) skips the check.

NOTES
  * Keys are generated by riddler; this tool cannot set a chosen key.
  * Tenant keys are stored in PLAINTEXT in the operations database, which is their only home.
    For every tenant -- including the default "fluid" one -- that is durable: nothing resets
    them, and get-key re-reads a key whenever it is needed.
  * rotate refuses to rotate the key a token service is currently signing with, because riddler
    invalidates the old key immediately and minting would break until the new value reached
    Key Vault. Rotate the OTHER key first, publish it, then come back. --force overrides.
  * Deleting a tenant does not delete its gitrest repository; gitrest has no delete route.
  * If a tenant is ever added directly to the Helm chart's riddler.tenants values instead of
    through this tool, rotate/delete will refuse it by default (--force overrides, but
    riddler re-upserts such a tenant from that static config on every restart, silently undoing
    the change).
`;

/**
 * Parse argv into { command, positionals, flags }.
 * Supports "--flag value", "--flag=value" and boolean "--flag".
 */
function parseArgs(argv) {
	const flags = {};
	const positionals = [];
	for (let i = 0; i < argv.length; i++) {
		const arg = argv[i];
		if (!arg.startsWith("--")) {
			positionals.push(arg);
			continue;
		}
		const eq = arg.indexOf("=");
		if (eq !== -1) {
			flags[arg.slice(2, eq)] = arg.slice(eq + 1);
			continue;
		}
		const name = arg.slice(2);
		const next = argv[i + 1];
		if (next === undefined || next.startsWith("--")) {
			flags[name] = true;
		} else {
			flags[name] = next;
			i++;
		}
	}
	return { command: positionals[0], positionals: positionals.slice(1), flags };
}

function flagOrEnv(flags, flagName, envName, fallback) {
	const value = flags[flagName];
	if (typeof value === "string" && value !== "") {
		return value;
	}
	const fromEnv = process.env[envName];
	if (typeof fromEnv === "string" && fromEnv !== "") {
		return fromEnv;
	}
	return fallback;
}

function buildManager(flags) {
	const correlationId = randomUUID();
	const timeoutMs = numericFlag(flags, "timeout-ms");

	const riddlerUrl = flagOrEnv(
		flags,
		"riddler-url",
		"TENANT_ADMIN_RIDDLER_URL",
		"http://fluid-riddler",
	);
	const gitrestUrl = flagOrEnv(
		flags,
		"gitrest-url",
		"TENANT_ADMIN_GITREST_URL",
		"http://gitrest",
	);
	const historianUrl = flagOrEnv(
		flags,
		"historian-url",
		"TENANT_ADMIN_HISTORIAN_URL",
		"http://historian",
	);
	const storageOwner = flagOrEnv(
		flags,
		"storage-owner",
		"TENANT_ADMIN_STORAGE_OWNER",
		"fluid",
	);
	// What gets written into the tenant document, which may differ from how we reach gitrest.
	const storageUrl = flagOrEnv(
		flags,
		"storage-url",
		"TENANT_ADMIN_STORAGE_URL",
		gitrestUrl,
	);

	return new TenantManager({
		riddler: new RiddlerClient({
			baseUrl: riddlerUrl,
			timeoutMs,
			correlationId,
		}),
		gitrest: new GitrestClient({
			baseUrl: gitrestUrl,
			owner: storageOwner,
			timeoutMs,
			correlationId,
		}),
		gitrestUrl: storageUrl,
		historianUrl,
	});
}

function requirePositional(positionals, name) {
	const value = positionals[0];
	if (!value) {
		throw new ValidationError(`Missing required argument <${name}>.`);
	}
	return value;
}

function requireFlag(flags, name) {
	const value = flags[name];
	if (typeof value !== "string" || value === "") {
		throw new ValidationError(`Missing required option --${name}.`);
	}
	return value;
}

/**
 * Read a flag that must carry a value, as a number.
 *
 * parseArgs sets a flag to boolean `true` when it is the last token or is followed by another
 * --flag. Coercing that with Number() yields 1, which silently turns a malformed
 * `--purge-in-days` into "purge in 1 day" and a malformed `--timeout-ms` into a 1ms timeout.
 * Both pass a plain isFinite() check, so the boolean has to be rejected explicitly.
 */
function numericFlag(flags, name) {
	const value = flags[name];
	if (value === undefined) {
		return undefined;
	}
	if (typeof value !== "string" || value.trim() === "") {
		throw new ValidationError(`--${name} requires a numeric value.`);
	}
	const parsed = Number(value);
	if (!Number.isFinite(parsed)) {
		throw new ValidationError(`--${name} must be a number (got "${value}").`);
	}
	return parsed;
}

/**
 * Look up the Key Vault secret the token service signs this tenant's tokens with, for the
 * `rotate` safety check.
 *
 * The read happens here, inside the cluster, because the vault is reachable only through its
 * private endpoint in the AKS VNet -- see src/keyVaultClient.js. `--keyvault-name` is passed by
 * ../tenant-admin.sh from deploy.parameters.json; without it there is no vault to consult.
 *
 * Returns a `status` alongside the binding because the wrapper runs this CLI with --json, which
 * silences note() so the `kubectl exec` stdout stream remains one machine-readable document.
 * The status therefore travels in the result instead, and the wrapper turns it back into
 * operator-facing text.
 *
 * A binding of undefined means there is genuinely nothing to protect. Anything that prevents the
 * check from running is fatal: not knowing whether a key is in use is not the same as knowing it
 * is free, and rotating blind is the outcome this check exists to prevent.
 */
async function resolveKeyVaultBinding(tenantId, flags, force) {
	// Force is checked before the vault name so the reported reason stays truthful:
	// tenant-admin.sh deliberately omits --keyvault-name when --force is given (it also keeps the
	// Pod out of the workload-identity webhook), and reporting that as "no vault configured"
	// would misattribute a deliberate override to a missing setting.
	if (force) {
		return { status: "skipped-forced" };
	}
	const vaultName = flags["keyvault-name"];
	if (typeof vaultName !== "string" || vaultName === "") {
		return { status: "skipped-no-vault" };
	}

	const secretName = secretNameForTenant(normalizeTenantId(tenantId));
	let result;
	try {
		result = await getSecret(vaultName, secretName);
	} catch (error) {
		if (error instanceof KeyVaultAccessError) {
			throw new ValidationError(
				`${error.message}\n` +
					`  tenant-admin therefore cannot tell whether "${tenantId}" is the key the ` +
					"token-minting Function App is signing with, and rotating blind would break token " +
					"minting until the new key reached the vault.\n" +
					"  Re-run with --force to skip this check.",
			);
		}
		throw error;
	}

	if (!result.found) {
		return { status: "skipped-no-secret", vaultName, secretName };
	}
	return {
		status: "performed",
		vaultName,
		secretName,
		binding: { vaultName, secretName, secretValue: result.value },
	};
}

async function main() {
	const { command, positionals, flags } = parseArgs(process.argv.slice(2));
	const jsonOnly = flags.json === true || flags.json === "true";
	const note = (message) => {
		if (!jsonOnly) {
			process.stderr.write(`${message}\n`);
		}
	};
	const emit = (value) => {
		process.stdout.write(`${JSON.stringify(value, undefined, 2)}\n`);
	};

	if (!command || command === "help" || flags.help) {
		process.stdout.write(`${USAGE}\n`);
		return 0;
	}

	const manager = buildManager(flags);
	const requestor = flags.requestor;
	const force = flags.force === true || flags.force === "true";

	switch (command) {
		case "create": {
			const tenantId = requirePositional(positionals, "tenantId");
			const contact = requireFlag(flags, "contact");
			const result = await manager.createTenant(tenantId, {
				contact,
				requestor,
			});
			note(
				`Created tenant "${result.tenantId}" (repository ${result.storage.owner}/${result.storage.repository}` +
					`${result.repositoryCreated ? " created" : " already existed"}).`,
			);
			note(
				"The key below is stored in PLAINTEXT in the operations database, which is its only " +
					"home. Re-read it later with: tenant-admin get-key " +
					result.tenantId,
			);
			if (result.customDataWarning) {
				note(`WARNING: ${result.customDataWarning}`);
			}
			emit(result);
			return 0;
		}
		case "get": {
			const tenantId = requirePositional(positionals, "tenantId");
			emit(await manager.getTenant(tenantId));
			return 0;
		}
		case "list": {
			const includeDisabled =
				flags["include-disabled"] === true ||
				flags["include-disabled"] === "true";
			const tenants = await manager.listTenants({ includeDisabled });
			note(`${tenants.length} tenant(s).`);
			emit(tenants);
			return 0;
		}
		case "get-key": {
			const tenantId = requirePositional(positionals, "tenantId");
			// Optional: --key key1|key2 narrows the output to one key.
			const keyName = typeof flags.key === "string" ? flags.key : undefined;
			note(
				keyName
					? `PRIVILEGED: printing the plaintext ${keyName} signing key.`
					: "PRIVILEGED: printing plaintext tenant signing keys.",
			);
			emit(await manager.getTenantKeys(tenantId, { keyName }));
			return 0;
		}
		case "rotate": {
			const tenantId = requirePositional(positionals, "tenantId");
			const keyName = requireFlag(flags, "key");
			const check = await resolveKeyVaultBinding(tenantId, flags, force);
			const result = await manager.rotateTenantKey(tenantId, keyName, {
				requestor,
				force,
				keyVaultBinding: check.binding,
			});
			// Carried in the result, not printed: see resolveKeyVaultBinding on why note() is
			// unavailable under --json. tenant-admin.sh renders these for the operator.
			result.keyVaultCheck = check.status;
			if (check.vaultName) {
				result.keyVaultName = check.vaultName;
				result.keyVaultSecretName = check.secretName;
			}
			note(
				`Rotated ${result.keyName} for "${result.tenantId}". Tokens signed with the other key remain valid.`,
			);
			note("Update any token service using this key.");
			if (result.metadataWarning) {
				note(`WARNING: ${result.metadataWarning}`);
			}
			emit(result);
			return 0;
		}
		case "set-contact": {
			const tenantId = requirePositional(positionals, "tenantId");
			const contact = requireFlag(flags, "contact");
			emit(await manager.updateContact(tenantId, contact, { requestor }));
			return 0;
		}
		case "delete": {
			const tenantId = requirePositional(positionals, "tenantId");
			const purgeNow =
				flags["purge-now"] === true || flags["purge-now"] === "true";
			const purgeInDays = numericFlag(flags, "purge-in-days");
			const result = await manager.deleteTenant(tenantId, {
				purgeInDays,
				purgeNow,
				force,
			});
			note(
				result.mode === "hard"
					? `Hard-deleted tenant "${result.tenantId}".`
					: `Soft-deleted (disabled) tenant "${result.tenantId}".`,
			);
			note(
				`gitrest repository ${result.orphanedRepository} was NOT removed (gitrest has no delete route).`,
			);
			emit(result);
			return 0;
		}
		default:
			process.stderr.write(`Unknown command "${command}".\n${USAGE}\n`);
			return 2;
	}
}

main()
	.then((code) => {
		process.exitCode = code;
	})
	.catch((error) => {
		// Never print the raw error object: httpClient redacts response bodies, but a stack dump
		// of an unexpected error could still carry request context. Message only.
		process.stderr.write(`ERROR: ${error.message}\n`);
		if (error.orphanedRepository) {
			process.stderr.write(
				`NOTE: gitrest repository "${error.orphanedRepository}" was created before the failure ` +
					"and was left in place. Retrying with the same tenant id reuses it.\n",
			);
		}
		process.exitCode = 1;
	});
