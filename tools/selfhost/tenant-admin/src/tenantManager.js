// Tenant lifecycle orchestration for the self-hosted Fluid stack.
//
// This module owns the ordering, the metadata and the cross-service consistency rules, and knows
// nothing about how it was invoked. The CLI in ../bin/tenant-admin.js is a thin caller. If an
// authenticated HTTP service is ever put in front of tenant management, it should call this class
// directly rather than reimplementing the logic -- that is the whole reason the transport is kept
// out of here.
//
// Two rules encoded below are worth calling out because getting them wrong is silent:
//
//   1. STORAGE IS CREATED BEFORE THE TENANT RECORD. gitrest's getOrCreateRepository is
//      idempotent, so an orphaned repository from a failed run is harmless and is reused on
//      retry. The reverse -- a tenant record whose repository does not exist -- is a tenant that
//      authenticates fine but fails every document operation, which is much harder to diagnose.
//
//   2. customData IS READ-MODIFY-WRITE. Riddler's PUT /customData replaces the entire object,
//      so a naive write drops createdBy/createdAt. See #alterCustomData.

"use strict";

const { GitrestClient } = require("./gitrestClient");
const { assertKeyNotInUse } = require("./keyVaultGuard");
const { RiddlerClient } = require("./riddlerClient");
const { normalizeContact, normalizeTenantId } = require("./validation");

const DEFAULT_HISTORIAN_URL = "http://historian";
const UNKNOWN_REQUESTOR = "unknown";

class TenantManager {
	/**
	 * @param {object} options
	 * @param {RiddlerClient} [options.riddler]
	 * @param {GitrestClient} [options.gitrest]
	 * @param {string} [options.gitrestUrl] recorded in the tenant's storage config
	 * @param {string} [options.historianUrl]
	 * @param {string} [options.internalHistorianUrl]
	 */
	constructor({
		riddler,
		gitrest,
		gitrestUrl,
		historianUrl = DEFAULT_HISTORIAN_URL,
		internalHistorianUrl,
	} = {}) {
		this.riddler = riddler ?? new RiddlerClient();
		this.gitrest = gitrest ?? new GitrestClient();
		// The URL riddler records in the tenant document. It must be resolvable from inside the
		// cluster by alfred/historian, which is not necessarily the URL this CLI used to reach
		// gitrest (e.g. when running through `kubectl port-forward`).
		this.gitrestUrl = gitrestUrl ?? this.gitrest.baseUrl;
		this.historianUrl = historianUrl;
		this.internalHistorianUrl = internalHistorianUrl ?? historianUrl;
	}

	#storageConfig(tenantId) {
		return {
			url: this.gitrestUrl,
			historianUrl: this.historianUrl,
			internalHistorianUrl: this.internalHistorianUrl,
			owner: this.gitrest.owner,
			repository: tenantId,
		};
	}

	/**
	 * Create a tenant: provision its snapshot repository, then register it with riddler.
	 *
	 * The returned key is generated by riddler, not by this tool -- riddler's API has no
	 * key-injection parameter. It is stored in plaintext in the operations database, which for
	 * tenants created here is its durable home: nothing re-upserts or resets them, so there is no
	 * second copy to keep in sync. Re-read it later with getTenantKeys().
	 *
	 * @param {string} rawTenantId
	 * @param {object} options
	 * @param {string} options.contact tenant admin contact (ownership metadata)
	 * @param {string} [options.requestor] who ran the command (self-asserted; see README)
	 * @returns {Promise<object>}
	 */
	async createTenant(rawTenantId, { contact, requestor } = {}) {
		const tenantId = normalizeTenantId(rawTenantId);
		const tenantAdminContact = normalizeContact(contact);
		const actor = normalizeRequestor(requestor);

		// Fail before touching storage if the id is taken. Riddler would reject the insert
		// anyway, but this keeps a failed run from leaving an unused repository behind.
		// includeDisabled matters: a soft-deleted tenant still occupies its _id, so without it
		// this check passes and the insert then fails on a duplicate key.
		const existing = await this.riddler.tryGetTenant(tenantId, {
			includeDisabled: true,
		});
		if (existing) {
			throw new Error(
				existing.disabled
					? `Tenant "${tenantId}" already exists but is soft-deleted. ` +
							`Purge it with "delete ${tenantId} --purge-now" before reusing the id.`
					: `Tenant "${tenantId}" already exists. Choose a different tenant id.`,
			);
		}

		// Step 1 -- storage first. See rule (1) at the top of this file.
		const repo = await this.gitrest.ensureRepository(tenantId);

		// Step 2 -- tenant record.
		const now = new Date().toISOString();
		const customData = {
			tenantAdminContact,
			createdBy: actor,
			createdAt: now,
			lastModifiedBy: actor,
			lastModifiedAt: now,
		};

		let created;
		try {
			created = await this.riddler.createTenant(tenantId, {
				storage: this.#storageConfig(tenantId),
				customData,
			});
		} catch (error) {
			// gitrest has no delete-repository route, so the repository cannot be rolled back
			// automatically. Surface it so the operator can remove it by hand if they choose --
			// leaving it is safe, and a retry with the same id reuses it.
			error.orphanedRepository = repo.created ? `${repo.owner}/${repo.repository}` : undefined;
			throw error;
		}

		// Riddler stamps `customData.encryptionKeyVersion = getLatestKeyVersion()` onto every
		// tenant it creates. On this stack that value is a lie: the SecretManager in use is the
		// upstream pass-through stub, so the key it claims is encrypted under a "2022" key
		// encryption key is in fact stored in plaintext. Strip it rather than leave a field that
		// misreports the security properties of the record.
		//
		// Best-effort: the tenant already exists and is fully usable at this point, so a failure
		// here must not fail the command.
		let customDataWarning;
		try {
			await this.riddler.updateCustomData(tenantId, customData);
		} catch (error) {
			customDataWarning = `Tenant created, but clearing riddler's encryptionKeyVersion stamp failed: ${error.message}`;
		}

		return {
			tenantId,
			key: created?.key,
			secondaryKey: created?.secondaryKey,
			storage: this.#storageConfig(tenantId),
			repositoryCreated: repo.created,
			customData,
			customDataWarning,
		};
	}

	async getTenant(rawTenantId) {
		return this.riddler.getTenant(normalizeTenantId(rawTenantId));
	}

	async listTenants({ includeDisabled = false } = {}) {
		return this.riddler.listTenants({ includeDisabled });
	}

	/**
	 * PRIVILEGED. Returns plaintext signing keys for the tenant.
	 *
	 * @param {object} [options]
	 * @param {"key1"|"key2"} [options.keyName] return only this key. When omitted, both are
	 *   returned. Riddler always sends both, so this filters the response rather than making a
	 *   narrower request -- useful for scripting (`--key key1 | jq -r .key1`) and for not putting
	 *   the key you did not ask for on screen.
	 */
	async getTenantKeys(rawTenantId, { keyName } = {}) {
		if (keyName !== undefined && keyName !== "key1" && keyName !== "key2") {
			throw new Error(`Invalid key name "${keyName}". Use key1 or key2.`);
		}
		const keys = await this.riddler.getTenantKeys(normalizeTenantId(rawTenantId));
		if (!keyName) {
			return keys;
		}
		return { [keyName]: keys?.[keyName] };
	}

	/**
	 * PRIVILEGED. Rotate one of the tenant's two shared keys.
	 *
	 * Rotate key2 first, move clients onto it, then rotate key1 (or the reverse) for a
	 * zero-downtime rotation: tokens signed with the untouched key stay valid throughout.
	 *
	 * `keyVaultBinding` enables the safety check in ./keyVaultGuard.js, which refuses to rotate
	 * the key a token service is actively signing with. It is supplied by ../tenant-admin.sh,
	 * the only caller that can read Key Vault; calling this method directly without it rotates
	 * unguarded.
	 *
	 * @param {"key1"|"key2"} keyName
	 * @param {object} [options]
	 * @param {string} [options.requestor]
	 * @param {boolean} [options.force] skip both the bootstrap-managed and in-use checks
	 * @param {{ vaultName: string, secretName: string, secretValue: string }} [options.keyVaultBinding]
	 */
	async rotateTenantKey(
		rawTenantId,
		keyName,
		{ requestor, force = false, keyVaultBinding } = {},
	) {
		if (keyName !== "key1" && keyName !== "key2") {
			throw new Error(`Invalid key name "${keyName}". Use key1 or key2.`);
		}
		const tenantId = normalizeTenantId(rawTenantId);
		// Confirm the tenant exists first so a typo reports "not found" instead of a riddler 500.
		const tenant = await this.riddler.getTenant(tenantId);
		assertNotBootstrapManaged(tenant, tenantId, "rotate the key of", force);

		// Read the current key BEFORE rotating, so the comparison still has something to compare.
		// Skipped entirely when there is no binding, to keep the unguarded path at one riddler
		// call as before.
		if (keyVaultBinding && !force) {
			const currentKeys = await this.riddler.getTenantKeys(tenantId);
			assertKeyNotInUse({
				tenantId,
				keyName,
				currentKey: currentKeys?.[keyName],
				keyVaultBinding,
				force,
			});
		}

		const keys = await this.riddler.rotateTenantKey(tenantId, keyName);

		// From here on the rotation has ALREADY happened: riddler persisted the new key and
		// invalidated its cache, so tokens signed with the old key are dead. The customData bump
		// below is cosmetic (lastModified* only), so it must never be allowed to throw -- doing
		// so would discard `keys` and leave the operator with a failed command, no key value and
		// no indication that the destructive step succeeded.
		let metadataWarning;
		try {
			await this.#alterCustomData(tenantId, {}, requestor);
		} catch (error) {
			metadataWarning =
				`Key ${keyName} was rotated successfully, but updating the lastModified metadata ` +
				`failed: ${error.message}`;
		}
		return { tenantId, keyName, keys, metadataWarning };
	}

	async updateContact(rawTenantId, contact, { requestor } = {}) {
		const tenantId = normalizeTenantId(rawTenantId);
		const tenantAdminContact = normalizeContact(contact);
		await this.riddler.getTenant(tenantId);
		const customData = await this.#alterCustomData(
			tenantId,
			{ tenantAdminContact },
			requestor,
		);
		return { tenantId, customData };
	}

	/**
	 * Delete a tenant.
	 *
	 * Defaults to a SOFT delete (riddler flags the document `disabled: true` and keeps it).
	 * `purgeNow` removes the document outright. Neither deletes the snapshot repository --
	 * gitrest exposes no delete route, so that is a manual step on the volume.
	 *
	 * @param {object} options
	 * @param {number} [options.purgeInDays] record a future purge date (still a soft delete now)
	 * @param {boolean} [options.purgeNow] hard-delete the document immediately
	 */
	async deleteTenant(rawTenantId, { purgeInDays, purgeNow = false, force = false } = {}) {
		const tenantId = normalizeTenantId(rawTenantId);

		// Validate arguments before any I/O so a bad flag reports the bad flag, rather than
		// whatever the first network call happens to say.
		let scheduledDeletionTime;
		if (purgeNow) {
			// Riddler hard-deletes only when the scheduled time is already in the past.
			scheduledDeletionTime = new Date(Date.now() - 60000);
		} else if (purgeInDays !== undefined) {
			if (!Number.isFinite(purgeInDays) || purgeInDays <= 0) {
				throw new Error("--purge-in-days must be a positive number.");
			}
			scheduledDeletionTime = new Date(Date.now() + purgeInDays * 24 * 60 * 60 * 1000);
		}

		// A soft-deleted tenant is hidden from riddler's default reads but its document -- and its
		// unique _id -- are still there. Purging one therefore has to look it up with
		// includeDisabled, or `delete --purge-now` after a default delete reports "not found" and
		// the record can never be removed through this tool.
		const tenant = await this.riddler.getTenant(tenantId, {
			includeDisabled: true,
		});
		assertNotBootstrapManaged(tenant, tenantId, "delete", force);
		await this.riddler.deleteTenant(tenantId, scheduledDeletionTime);
		return {
			tenantId,
			mode: purgeNow ? "hard" : "soft",
			scheduledDeletionTime: purgeNow ? undefined : scheduledDeletionTime?.toISOString(),
			orphanedRepository: `${this.gitrest.owner}/${tenantId}`,
		};
	}

	/**
	 * Merge changes into a tenant's customData, preserving fields this tool did not set and
	 * refreshing the lastModified* pair. Riddler's PUT is a whole-object replace.
	 */
	async #alterCustomData(tenantId, alterations, requestor) {
		const tenant = await this.riddler.getTenant(tenantId);
		const merged = {
			...(tenant.customData ?? {}),
			...alterations,
			lastModifiedBy: normalizeRequestor(requestor),
			lastModifiedAt: new Date().toISOString(),
		};
		await this.riddler.updateCustomData(tenantId, merged);
		return merged;
	}
}

/**
 * Guard destructive operations against any tenant seeded via the Helm chart's `riddler.tenants`
 * values, rather than created through this tool.
 *
 * This stack's own deployment (`azure/deploy.sh`) does not seed any tenant that way -- even the
 * default `fluid` tenant is created through this tool (see `phase5_bootstrap_tenant`) -- so this
 * guard is defensive: it only matters if a deployment (or a future change to this one) puts a
 * tenant back into `riddler.tenants`. Any tenant there is re-upserted by riddler's runnerFactory
 * on EVERY pod start, from config with no `key` field, so riddler would happily accept a key
 * rotation or delete on it and report success -- and then silently undo the change, at the next
 * pod restart. Worse, a delete leaves the tenant flagged `disabled` while the bootstrap upsert (a
 * `$set` of `_id`/`storage`/`key` only) never clears that flag, so the tenant stays broken.
 *
 * Detection is by absence of `customData.createdBy`: every tenant this tool creates stamps it,
 * and a Helm-seeded tenant has no customData at all (riddler backfills an empty object).
 */
function assertNotBootstrapManaged(tenant, tenantId, operation, force) {
	if (force || tenant?.customData?.createdBy) {
		return;
	}
	throw new Error(
		`Refusing to ${operation} tenant "${tenantId}": it was not created by tenant-admin, so it ` +
			"is managed by the deployment's bootstrap path (added directly to Helm's " +
			"`riddler.tenants` values). Riddler re-upserts it from that static config on every " +
			"restart, so the change would be silently reverted at the next riddler restart.\n" +
			"  To rotate or remove such a tenant: take it out of (or update) the Helm values and " +
			"upgrade the release.\n" +
			"  Pass --force only if you understand the change will not survive.",
	);
}

/**
 * The requestor is self-asserted: with direct-cluster-access administration (the model this tool
 * is built for) there is no authenticated identity to derive it from. tenant-admin.sh
 * fills it in from the signed-in Azure CLI account, which is accurate in practice but is still
 * an audit breadcrumb, not an authorization decision.
 */
function normalizeRequestor(requestor) {
	if (typeof requestor === "string" && requestor.trim() !== "") {
		return requestor.trim().toLowerCase();
	}
	const fromEnv = process.env.TENANT_ADMIN_REQUESTOR;
	if (typeof fromEnv === "string" && fromEnv.trim() !== "") {
		return fromEnv.trim().toLowerCase();
	}
	return UNKNOWN_REQUESTOR;
}

module.exports = {
	TenantManager,
	assertNotBootstrapManaged,
	DEFAULT_HISTORIAN_URL,
	UNKNOWN_REQUESTOR,
	normalizeRequestor,
};
