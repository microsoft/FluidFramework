import type { readFile } from "node:fs/promises";

import type { Heading, Root, RootContent } from "mdast";

/**
 * A documentation format that Markdown Magic can process.
 */
export type DocumentFormat = "markdown" | "mdx";

/**
 * A parsed documentation file and the source details needed for range replacement.
 */
export interface ParsedDocument {
	/**
	 * The syntax used by the document.
	 */
	readonly format: DocumentFormat;

	/**
	 * The path used to parse the document and report errors.
	 */
	readonly path: string;

	/**
	 * The original document text.
	 */
	readonly source: string;

	/**
	 * The parsed Markdown syntax tree.
	 */
	readonly tree: Root;
}

/**
 * Diagnostic metadata attached to generated nodes.
 */
interface GeneratedNodeMetadata {
	/**
	 * The source path to report when generated content cannot be serialized.
	 */
	readonly sourcePath?: string;
}

/**
 * Markdown syntax-tree nodes generated by a transform, with optional diagnostic metadata.
 */
export type GeneratedNodes = RootContent[] & GeneratedNodeMetadata;

/**
 * Services and destination details that are available to a transform.
 */
export interface TransformContext {
	/**
	 * The absolute path of the document that contains the generated region.
	 */
	readonly destinationPath: string;

	/**
	 * The syntax used by the destination document.
	 */
	readonly destinationFormat: DocumentFormat;

	/**
	 * The heading depth assigned to the generated section.
	 */
	readonly sectionHeadingDepth: Heading["depth"];

	/**
	 * Resolves a path relative to the destination document.
	 *
	 * @param relativePath - The destination-relative path to resolve.
	 * @returns The resolved absolute path.
	 */
	resolvePath(relativePath: string): string;

	/**
	 * Parses documentation text using the parser selected by the file extension.
	 *
	 * @param source - The documentation text to parse.
	 * @param filePath - The path used to select a parser and report errors.
	 * @returns The parsed document and its source details.
	 */
	readonly parseDocument: (source: string, filePath: string) => ParsedDocument;

	/**
	 * Reads source files for the transform.
	 */
	readonly readFile: typeof readFile;
}

/**
 * A transform that validates marker options and generates syntax-tree nodes.
 */
export interface Transform {
	/**
	 * Generates content for a marked region.
	 *
	 * @param options - The untrusted options from the region marker.
	 * @param context - The services and destination details for the transform.
	 * @returns The generated nodes, either directly or in a promise.
	 */
	generate(
		options: unknown,
		context: TransformContext,
	): GeneratedNodes | Promise<GeneratedNodes>;
}

/**
 * A registry that contains transforms and creates their execution context.
 */
export interface TransformRegistry {
	/**
	 * The transforms indexed by marker name.
	 */
	readonly transforms: Readonly<Record<string, Transform>>;

	/**
	 * Creates the context for a generated region.
	 *
	 * @param destinationPath - The absolute path of the destination document.
	 * @param destinationFormat - The syntax used by the destination document.
	 * @param sectionHeadingDepth - The heading depth assigned to the generated section.
	 * @returns The context for executing a transform.
	 */
	createContext(
		destinationPath: string,
		destinationFormat: DocumentFormat,
		sectionHeadingDepth: Heading["depth"],
	): TransformContext;
}

/**
 * A generated region in a destination document.
 */
export interface GeneratedRegion {
	/**
	 * The absolute path of the destination document.
	 */
	readonly destinationPath: string;

	/**
	 * The syntax used by the destination document.
	 */
	readonly destinationFormat: DocumentFormat;

	/**
	 * The marker name of the transform to execute.
	 */
	readonly transformName: string;

	/**
	 * The untrusted options from the region marker.
	 */
	readonly options: Record<string, unknown>;

	/**
	 * The source offset immediately after the opening marker.
	 */
	readonly openingMarkerEnd: number;

	/**
	 * The source offset at the start of the closing marker.
	 */
	readonly closingMarkerStart: number;

	/**
	 * The one-based line of the opening marker.
	 */
	readonly line: number;
}
